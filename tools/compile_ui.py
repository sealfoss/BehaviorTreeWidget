"""Compile the packaged Qt Designer files into Python forms. Run it after editing a ``.ui`` file.

    python tools/compile_ui.py            # (re)generate src/behavior_tree_widget/_forms/
    python tools/compile_ui.py --check    # exit status 1 if a form is missing or out of date

For every ``src/behavior_tree_widget/ui/<Name>.ui`` this runs ``pyside6-uic`` and writes
``src/behavior_tree_widget/_forms/ui_<Name>.py``, and it writes the index
``src/behavior_tree_widget/_forms/__init__.py``. The index records, per ``.ui`` file, the generated
module, its ``Ui_`` class, the class of the form's top-level widget and the SHA-256 of the ``.ui``
file (with ``\\r\\n`` read as ``\\n``, so the hash does not depend on how git checked the file out).

``behavior_tree_widget._ui.load_ui`` builds a packaged form from its generated module, which is much
faster than parsing the XML with ``QUiLoader``. A ``.ui`` file whose hash does not match the index
(edited, but not compiled again) is still loaded with ``QUiLoader``, so it works, only slower; the
test-suite fails until the forms are compiled again.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from xml.etree import ElementTree

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "src" / "behavior_tree_widget"
UI_FOLDER = PACKAGE / "ui"
FORMS_FOLDER = PACKAGE / "_forms"
INDEX = FORMS_FOLDER / "__init__.py"

INDEX_HEADER = '''"""Python forms of the packaged Qt Designer files, generated by tools/compile_ui.py. Do not edit.

``FORMS`` maps each ``.ui`` file name of ``behavior_tree_widget/ui`` to a :class:`Form`: the module
(in this package) holding its generated ``Ui_`` class, that class's name, the class of the form's
top-level widget (in ``PySide6.QtWidgets``) and the SHA-256 of the ``.ui`` file it was generated from
(``\\r\\n`` read as ``\\n``). See ``behavior_tree_widget._ui.load_ui``.
"""

from __future__ import annotations

from typing import NamedTuple


class Form(NamedTuple):
    module: str
    ui_class: str
    widget_class: str
    sha256: str


'''


def ui_hash(data: bytes) -> str:
    """SHA-256 of a ``.ui`` file's content, independent of its line endings."""
    return hashlib.sha256(data.replace(b"\r\n", b"\n")).hexdigest()


def find_uic() -> list[str]:
    """The command running pyside6-uic (Python generator)."""
    names = ["pyside6-uic.exe", "pyside6-uic"] if os.name == "nt" else ["pyside6-uic"]
    folders = [Path(sys.executable).parent, Path(sys.executable).parent / "Scripts"]
    for folder in folders:
        for name in names:
            candidate = folder / name
            if candidate.is_file():
                return [str(candidate)]
    found = shutil.which("pyside6-uic")
    if found:
        return [found]
    raise SystemExit("pyside6-uic was not found: install PySide6 in this Python environment")


def top_level_widget(data: bytes, name: str) -> str:
    """The class of the form's top-level widget (``QWidget``, ``QFrame``, ...)."""
    root = ElementTree.fromstring(data)
    widget = root.find("widget")
    if widget is None or not widget.get("class"):
        raise SystemExit(f"{name}: no top-level <widget> element")
    widget_class = widget.get("class")
    if not re.fullmatch(r"Q[A-Za-z]+", widget_class):
        raise SystemExit(f"{name}: the top-level widget class {widget_class!r} is not a QtWidgets class")
    return widget_class


def compile_ui(uic: list[str], source: Path, target: Path) -> str:
    """Generate ``target`` from ``source``; returns the name of its ``Ui_`` class."""
    with tempfile.TemporaryDirectory() as folder:
        output = Path(folder) / target.name
        result = subprocess.run(
            [*uic, str(source), "-o", str(output)],
            stdin=subprocess.DEVNULL,
            capture_output=True,
            text=True,
            timeout=120,
            check=False,
        )
        if result.returncode != 0 or not output.is_file():
            raise SystemExit(f"pyside6-uic failed for {source.name}:\n{result.stdout}{result.stderr}")
        code = output.read_text(encoding="utf-8")
    match = re.search(r"^class (Ui_\w+)\(object\):", code, re.MULTILINE)
    if match is None:
        raise SystemExit(f"{source.name}: pyside6-uic generated no Ui_ class")
    code = code.replace("\r\n", "\n")
    target.write_text(code, encoding="utf-8", newline="\n")
    return match.group(1)


def index_text(entries: dict[str, tuple[str, str, str, str]]) -> str:
    lines = [INDEX_HEADER, "FORMS: dict[str, Form] = {\n"]
    for name, (module, ui_class, widget_class, digest) in sorted(entries.items()):
        lines.append(f"    {name!r}: Form({module!r}, {ui_class!r}, {widget_class!r}, {digest!r}),\n")
    lines.append("}\n")
    return "".join(lines)


def ui_files() -> list[Path]:
    return sorted(UI_FOLDER.glob("*.ui"))


def module_name(source: Path) -> str:
    return f"ui_{source.stem}"


def check() -> int:
    """Report forms that are missing or out of date (exit status 1), as the test-suite does."""
    sys.path.insert(0, str(PACKAGE.parent))
    try:
        from behavior_tree_widget._forms import FORMS
    except ImportError:
        print("the generated forms are missing: run python tools/compile_ui.py")
        return 1
    problems = []
    for source in ui_files():
        form = FORMS.get(source.name)
        if form is None or not (FORMS_FOLDER / f"{form.module}.py").is_file():
            problems.append(f"{source.name}: no generated form")
        elif form.sha256 != ui_hash(source.read_bytes()):
            problems.append(f"{source.name}: changed since its form was generated")
    problems += [f"{name}: the .ui file no longer exists" for name in FORMS if not (UI_FOLDER / name).is_file()]
    for problem in problems:
        print(problem)
    if problems:
        print("run python tools/compile_ui.py")
        return 1
    print(f"{len(FORMS)} forms are up to date")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="only check that every form is up to date")
    arguments = parser.parse_args(argv)
    if arguments.check:
        return check()
    uic = find_uic()
    FORMS_FOLDER.mkdir(exist_ok=True)
    entries: dict[str, tuple[str, str, str, str]] = {}
    for source in ui_files():
        data = source.read_bytes()
        module = module_name(source)
        ui_class = compile_ui(uic, source, FORMS_FOLDER / f"{module}.py")
        entries[source.name] = (module, ui_class, top_level_widget(data, source.name), ui_hash(data))
        print(f"{source.name} -> _forms/{module}.py ({ui_class})")
    wanted = {f"{module}.py" for module, _, _, _ in entries.values()} | {"__init__.py"}
    for stale in FORMS_FOLDER.glob("ui_*.py"):
        if stale.name not in wanted:
            stale.unlink()
            print(f"removed _forms/{stale.name}")
    INDEX.write_text(index_text(entries), encoding="utf-8", newline="\n")
    print(f"wrote {INDEX.relative_to(ROOT)} ({len(entries)} forms)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
